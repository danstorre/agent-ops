// Behavior eval: the whole agent on real conversations. Needs an OpenAI key (OPENAI_API_KEY or OPENAI_KEY):
//   npx tsx --env-file=path/to/.env scripts/eval-behavior.ts [model] [comma-separated case ids]
// Each finished conversation is saved to evals/runs/behavior-<model>.jsonl, so a run that hits a rate
// limit stops cleanly and the next run resumes where it stopped. Writes docs/evals/behavior.md.
import { existsSync, mkdirSync, readFileSync, appendFileSync, writeFileSync } from "node:fs";
import { runAgent } from "../src/agent/loop.js";
import { openAIClient, OPENAI_PRICES, GPT_4O_PRICES } from "../src/agent/openai.js";
import { SYSTEM_PROMPT } from "../src/agent/prompt.js";
import { storeTools } from "../src/agent/store-agent.js";
import { buildPolicyStore } from "../src/tools/policies.js";
import { grade, allowedPrices, type BehaviorCase, type CheckResult } from "../src/evals/behavior.js";
import type { AgentResult } from "../src/agent/loop.js";

const MODEL = process.argv[2] ?? "gpt-4o";
const allCases = JSON.parse(readFileSync(new URL("../evals/behavior-cases.json", import.meta.url), "utf8")) as BehaviorCase[];
const only = process.argv[3]?.split(",").filter(Boolean);
const cases = only ? allCases.filter((c) => only.includes(c.id)) : allCases;
const PRICES = OPENAI_PRICES[MODEL] ?? GPT_4O_PRICES;
const runsDir = new URL("../evals/runs/", import.meta.url);
const runFile = new URL(`behavior-${MODEL}.jsonl`, runsDir);
mkdirSync(runsDir, { recursive: true });

type Saved = { id: string; reply: string; handedOff: boolean; handoffReason?: string; log: AgentResult["log"]; costUsd: number; messages?: AgentResult["messages"] };
const saved = new Map<string, Saved>(
  existsSync(runFile) ? readFileSync(runFile, "utf8").trim().split("\n").filter(Boolean).map((l) => [JSON.parse(l).id, JSON.parse(l)]) : [],
);

const todo = cases.filter((c) => !saved.has(c.id));
let stoppedBy: string | undefined;
if (todo.length) {
  const policies = await buildPolicyStore();
  const createMessage = openAIClient({ model: MODEL });
  for (const c of todo) {
    try {
      const r = await runAgent({ createMessage, system: SYSTEM_PROMPT, tools: storeTools(policies), userMessage: c.message, model: MODEL, prices: PRICES });
      const row: Saved = { id: c.id, reply: r.reply, handedOff: r.handedOff, handoffReason: r.handoffReason, log: r.log, costUsd: r.costUsd, messages: r.messages };
      appendFileSync(runFile, JSON.stringify(row) + "\n");
      saved.set(c.id, row);
      console.log(`done ${c.id}`);
    } catch (error) {
      const status = (error as { status?: number }).status;
      stoppedBy = status === 429 ? "the provider's rate limit" : `an error: ${String(error).slice(0, 120)}`;
      console.error(`stopped at ${c.id} by ${stoppedBy}`);
      break;
    }
  }
  await policies.close();
}

const allowed = allowedPrices();
const rows = cases.filter((c) => saved.has(c.id)).map((c) => {
  const s = saved.get(c.id)!;
  const checks = grade(c, s as unknown as AgentResult, allowed);
  return { c, s, checks, tools: [...new Set(s.log.flatMap((t) => t.tools))] };
});

const names: CheckResult["name"][] = ["right tool", "correct handoff", "citation present", "no invented prices"];
const summary = names.map((name) => {
  const applicable = rows.map((r) => r.checks.find((k) => k.name === name)!).filter((k) => k.applies);
  return { name, passed: applicable.filter((k) => k.passed).length, total: applicable.length };
});
const allPassed = rows.filter((r) => r.checks.every((k) => !k.applies || k.passed)).length;
const cost = rows.reduce((sum, r) => sum + r.s.costUsd, 0);
const pct = (n: number, d: number) => `${n}/${d} (${d ? Math.round((100 * n) / d) : 0}%)`;
const cell = (t: string) => t.replace(/\|/g, "\\|").replace(/\n+/g, " ");
const partial = rows.length < cases.length;

writeFileSync(
  new URL(`../docs/evals/behavior-${MODEL}.md`, import.meta.url),
  [
    `# Behavior eval: ${MODEL}`,
    "",
    `The whole agent (same loop, tools, retrieval and prompt) on single-message conversations, one run each, with \`${MODEL}\` through the OpenAI adapter. Generated by \`scripts/eval-behavior.ts\`; do not edit by hand.`,
    "",
    partial
      ? `**Partial run: ${rows.length} of ${cases.length} conversations.** The OpenAI account used here allows 50 requests a day per model, and each conversation takes two to four.`
      : only
        ? `A representative subset of ${cases.length} of the ${allCases.length} conversations (the account used here allows 50 requests a day per model). With this few cases, one or two conversations is within noise.`
        : `All ${cases.length} conversations, one run each: a difference of one or two cases between runs is within noise.`,
    "",
    "| Check | Passed |",
    "|---|---|",
    ...summary.map((x) => `| ${x.name} | ${pct(x.passed, x.total)} |`),
    `| **all checks in a conversation** | **${pct(allPassed, rows.length)}** |`,
    "",
    `Estimated cost of these conversations: USD ${cost.toFixed(4)} at ${MODEL} list prices.`,
    "",
    "## Per conversation",
    "",
    "| id | message | tools called | failed checks | reply |",
    "|---|---|---|---|---|",
    ...rows.map((r) => `| ${r.c.id} | ${cell(r.c.message)} | ${r.tools.join(", ") || "none"} | ${r.checks.filter((k) => k.applies && !k.passed).map((k) => `${k.name} (${cell(k.detail)})`).join("; ") || "none"} | ${cell(r.s.reply).slice(0, 220)} |`),
    "",
  ].join("\n"),
);
console.log(`${rows.length}/${cases.length} conversations${stoppedBy ? `, stopped by ${stoppedBy}` : ""}\n${summary.map((x) => `${x.name}: ${pct(x.passed, x.total)}`).join("\n")}\nall checks: ${pct(allPassed, rows.length)}\ncost: USD ${cost.toFixed(3)}`);
