// Retrieval eval: npm run eval:retrieval
// Runs every case against the real local model and the keyword baseline, writes
// docs/evals/retrieval.md and fails (exit 1) if hit@3 drops below the gate.
import { readFileSync, writeFileSync } from "node:fs";
import { localEmbedder } from "../src/rag/embed.js";
import { keywordEmbedder } from "../src/rag/keyword-embedder.js";
import { buildPolicyStore } from "../src/tools/policies.js";
import { evaluateRetrieval, summarize, type RetrievalCase, type RetrievalRow } from "../src/evals/retrieval.js";

const GATE_HIT_AT_3 = Number(process.env.GATE_HIT_AT_3 ?? 0);
const cases = JSON.parse(readFileSync(new URL("../evals/retrieval-cases.json", import.meta.url), "utf8")) as RetrievalCase[];

async function run(name: string, embed: Parameters<typeof buildPolicyStore>[0]) {
  const store = await buildPolicyStore(embed);
  const rows = await evaluateRetrieval((q, k) => store.search(q, k), cases);
  await store.close();
  return { name, rows, summary: summarize(rows) };
}

const model = await run("local embeddings (all-MiniLM-L6-v2)", localEmbedder());
const baseline = await run("keyword baseline (word overlap)", keywordEmbedder);

const pct = (n: number, d: number) => `${n}/${d} (${Math.round((100 * n) / d)}%)`;
const line = (r: { name: string; summary: ReturnType<typeof summarize> }) =>
  `| ${r.name} | ${pct(r.summary.hitAt1, r.summary.answerable)} | ${pct(r.summary.hitAt3, r.summary.answerable)} |`;
const mark = (row: RetrievalRow) => (row.expected.length === 0 ? "n/a" : row.rank === null ? "miss" : `#${row.rank}`);

const report = [
  "# Retrieval eval",
  "",
  `${cases.length} customer questions (${cases.filter((c) => c.author === "dan").length} written by Dan, the rest by Claude), each labeled with the policy sections that answer it. Generated by \`npm run eval:retrieval\`; do not edit by hand.`,
  "",
  "| Retriever | Right section first (hit@1) | Right section in the 3 Claude reads (hit@3) |",
  "|---|---|---|",
  line(model),
  line(baseline),
  "",
  `Questions the policies can't answer (${cases.filter((c) => c.expected.length === 0).length}) are not counted: the right behavior there is a handoff, which the behavior eval checks.`,
  "",
  "## Per question (local embeddings vs keyword baseline)",
  "",
  "| id | question | expected | model | baseline | model top 3 |",
  "|---|---|---|---|---|---|",
  ...model.rows.map((row, i) => `| ${row.id} | ${row.question} | ${row.expected.join(", ") || "none"} | ${mark(row)} | ${mark(baseline.rows[i]!)} | ${row.got.join(", ")} |`),
  "",
].join("\n");
writeFileSync(new URL("../docs/evals/retrieval.md", import.meta.url), report);

console.log(`model    hit@1 ${pct(model.summary.hitAt1, model.summary.answerable)}  hit@3 ${pct(model.summary.hitAt3, model.summary.answerable)}`);
console.log(`baseline hit@1 ${pct(baseline.summary.hitAt1, baseline.summary.answerable)}  hit@3 ${pct(baseline.summary.hitAt3, baseline.summary.answerable)}`);
for (const row of model.rows.filter((r) => r.expected.length > 0 && r.rank !== 1)) console.log(`  ${mark(row).padEnd(5)} ${row.id} "${row.question}" expected ${row.expected.join("|")} got ${row.got.join(", ")}`);
if (model.summary.hitAt3 < GATE_HIT_AT_3) {
  console.error(`GATE FAILED: hit@3 ${model.summary.hitAt3} < ${GATE_HIT_AT_3}`);
  process.exit(1);
}
